//! Mapping from host physical keys to Amiga raw key codes (US layout positions).

use winit::keyboard::KeyCode;

pub fn amiga_scancode(code: KeyCode) -> Option<u8> {
    use KeyCode::*;
    Some(match code {
        Backquote => 0x00,
        Digit1 => 0x01,
        Digit2 => 0x02,
        Digit3 => 0x03,
        Digit4 => 0x04,
        Digit5 => 0x05,
        Digit6 => 0x06,
        Digit7 => 0x07,
        Digit8 => 0x08,
        Digit9 => 0x09,
        Digit0 => 0x0A,
        Minus => 0x0B,
        Equal => 0x0C,
        Backslash => 0x0D,
        Numpad0 => 0x0F,
        KeyQ => 0x10,
        KeyW => 0x11,
        KeyE => 0x12,
        KeyR => 0x13,
        KeyT => 0x14,
        KeyY => 0x15,
        KeyU => 0x16,
        KeyI => 0x17,
        KeyO => 0x18,
        KeyP => 0x19,
        BracketLeft => 0x1A,
        BracketRight => 0x1B,
        Numpad1 => 0x1D,
        Numpad2 => 0x1E,
        Numpad3 => 0x1F,
        KeyA => 0x20,
        KeyS => 0x21,
        KeyD => 0x22,
        KeyF => 0x23,
        KeyG => 0x24,
        KeyH => 0x25,
        KeyJ => 0x26,
        KeyK => 0x27,
        KeyL => 0x28,
        Semicolon => 0x29,
        Quote => 0x2A,
        Numpad4 => 0x2D,
        Numpad5 => 0x2E,
        Numpad6 => 0x2F,
        IntlBackslash => 0x30,
        KeyZ => 0x31,
        KeyX => 0x32,
        KeyC => 0x33,
        KeyV => 0x34,
        KeyB => 0x35,
        KeyN => 0x36,
        KeyM => 0x37,
        Comma => 0x38,
        Period => 0x39,
        Slash => 0x3A,
        NumpadDecimal => 0x3C,
        Numpad7 => 0x3D,
        Numpad8 => 0x3E,
        Numpad9 => 0x3F,
        Space => 0x40,
        Backspace => 0x41,
        Tab => 0x42,
        NumpadEnter => 0x43,
        Enter => 0x44,
        Escape => 0x45,
        Delete => 0x46,
        NumpadSubtract => 0x4A,
        ArrowUp => 0x4C,
        ArrowDown => 0x4D,
        ArrowRight => 0x4E,
        ArrowLeft => 0x4F,
        F1 => 0x50,
        F2 => 0x51,
        F3 => 0x52,
        F4 => 0x53,
        F5 => 0x54,
        F6 => 0x55,
        F7 => 0x56,
        F8 => 0x57,
        F9 => 0x58,
        F10 => 0x59,
        NumpadParenLeft => 0x5A,
        NumpadParenRight => 0x5B,
        NumpadDivide => 0x5C,
        NumpadMultiply => 0x5D,
        NumpadAdd => 0x5E,
        // The Amiga Help key has no PC equivalent; Insert and F11 are close by.
        Help | Insert | F11 => 0x5F,
        ShiftLeft => 0x60,
        ShiftRight => 0x61,
        CapsLock => 0x62,
        ControlLeft | ControlRight => 0x63,
        AltLeft => 0x64,
        AltRight => 0x65,
        // Amiga keys: the Command / Windows keys.
        SuperLeft => 0x66,
        SuperRight => 0x67,
        _ => return None,
    })
}
